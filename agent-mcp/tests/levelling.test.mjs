// Levelling coach tests (roadmap Stage 7): the cited data file and the PoB-side
// engine (Agent/Handlers/Levelling.lua) in the headless engine. No network, no PoB
// window, nothing written to the player's Documents. Run with: npm test
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "agent-mcp-levelling-"));
const builds = path.join(tmp, "Builds");
fs.mkdirSync(builds);
fs.copyFileSync(path.join(here, "fixtures", "occ-vortex.xml"), path.join(builds, "occ-vortex.xml"));
process.env.POB_LIVE = "off";
process.env.POB_DIRECTORY = builds;
process.env.POB_AGENT_SETTINGS = path.join(tmp, "AgentEdition.json");
process.env.POB_AGENT_CACHE = path.join(tmp, "cache");
process.env.POB_AGENT_UPDATE_CHECK = "off";

const { createTools, runTool } = await import("../build/server.js");
const { tools, context } = createTools();

const dataFile = fs.readFileSync(path.join(root, "PathOfBuilding", "src", "Agent", "LevellingData.lua"), "utf8");

test("data file: generated, cited, with the facts the coach needs", () => {
  assert.match(dataFile, /^-- Levelling coach data \(Stage 7\)\. GENERATED by agent-mcp\/scripts\/levelling-data\.mjs/);
  assert.match(dataFile, /gameVersion = "\d+\.\d+\.\d+/);
  // Every text fact keeps its source key and a quote; sources have links.
  const facts = dataFile.slice(dataFile.indexOf("\tfacts = {"), dataFile.indexOf("\n\tgods = {"));
  const quotes = facts.match(/quote = "/g) ?? [];
  const srcs = facts.match(/src = "/g) ?? [];
  assert.ok(quotes.length >= 30, `facts keep their quotes (${quotes.length})`);
  assert.equal(quotes.length, srcs.length, "every quoted fact names its source");
  for (const key of ["passive", "lab", "trials", "bandits", "pantheon", "resist", "recipes", "sockets", "quests", "vendors", "areas"]) {
    assert.match(dataFile, new RegExp(`\\b${key} = \\{ title = "[^"]+", url = "https://www\\.poewiki\\.net/`), `source ${key} has a link`);
  }
  assert.match(dataFile, /Completion of Part One: -30% to all resistances/);
  assert.match(dataFile, /There are 23-24 total/);
  assert.equal((dataFile.slice(dataFile.indexOf("\tquestPoints = {"), dataFile.indexOf("\trefunds = {")).match(/\{ act = \d+, quest = /g) ?? []).length, 23);
  // No personal data, nothing from a player's account.
  assert.doesNotMatch(dataFile, /Users\\|POESESSID|@gmail/i);
  assert.ok(Buffer.byteLength(dataFile) < 120 * 1024, "data stays small (Stage 17)");
});

// --- headless: a level-34 copy of the fixture (smaller tree, no ascendancy points) ----
const ok = async (name, args = {}) => {
  const r = await runTool(tools, context, name, args);
  assert.equal(r.isError, false, `${name} failed: ${r.text}`);
  return r.text;
};
await ok("open_build", { name: "occ-vortex" });
const link = await context.pob.link();
const own = await link.call("levelling_guide_stages", { ids: true });
// Keep the first 40 points of the walking order; drop the rest and the ascendancy (last first).
const late = own.stages[0].walk.slice(40).reverse();
await link.call("edit", { ops: [{ op: "dealloc", nodes: late }, { op: "dealloc", nodes: own.stages[0].ascIds.slice().reverse() },
  { op: "config", values: { level: 34, resistancePenalty: 0 } }] });

test("levelling_guide_stages: the build's own tree in walking order, placed on levels", async () => {
  assert.equal(own.className, "Witch");
  const st = own.stages[0];
  assert.ok(st.passives.length > 10);
  for (let i = 1; i < st.passives.length; i++) assert.ok(st.passives[i].point > st.passives[i - 1].point, "points in walking order");
  for (let i = 1; i < st.passives.length; i++) assert.ok(st.passives[i].level >= st.passives[i - 1].level, "levels never go down");
  assert.ok(st.passives.every((p) => p.level >= 1 && p.level <= 100));
  assert.ok(st.asc.length >= 4, "ascendancy nodes in order");
  assert.equal(st.main.skill, "Vortex");
});

const plan = await link.call("levelling_plan", {});

test("levelling_plan: character, act and quest points from PoB", () => {
  assert.equal(plan.me.level, 34);
  assert.ok(plan.me.act >= 2 && plan.me.act <= 5, `act ${plan.me.act} estimated by PoB from the points`);
  assert.equal(plan.me.ascPoints, 0);
  assert.equal(plan.me.points, 40);
  assert.equal(plan.acts.length, 11, "Acts 1-10 plus maps");
  assert.equal(plan.acts.reduce((n, a) => n + a.questPoints.length, 0), 23);
  assert.equal(plan.questPoints.total, 23);
  assert.match(plan.questPoints.source.url, /poewiki\.net\/wiki\/Passive_skill/);
});

test("levelling_plan: gems placed by quest reward / vendor for the class and level", () => {
  const gems = plan.acts.flatMap((a) => a.gems.map((g) => ({ ...g, act: a.act })));
  const vortex = gems.find((g) => g.name === "Vortex");
  assert.ok(vortex, "the main skill is in the plan");
  assert.ok(vortex.act >= 3, "Vortex is not a Witch quest reward before Act 3");
  assert.match(vortex.text, /Act \d+: (buy from|quest reward)/);
  for (const g of gems) if (g.req) assert.ok(plan.acts[g.act - 1].levels[1] >= g.req || g.act === 11 || g.act >= 1, "a gem is never placed before its act");
});

test("levelling_plan: milestones (labs, bandit simulated, Pantheon) with sources", () => {
  const [normal, cruel, merciless, eternal] = plan.milestones.labs;
  assert.deepEqual([normal.name, cruel.name, merciless.name, eternal.name], ["Normal", "Cruel", "Merciless", "Eternal"]);
  assert.equal(normal.status, "next");
  assert.equal(normal.trials.length, 6);
  assert.equal(cruel.minLevel, 40);
  assert.equal(merciless.minLevel, 50);
  assert.equal(eternal.minLevel, 68);
  const b = plan.milestones.bandit;
  assert.equal(b.act, 2);
  assert.equal(b.options.length, 4);
  const alira = b.options.find((o) => o.config === "Alira");
  assert.ok(alira.gain && alira.gain.rolledBack === true, "bandit options are simulated and rolled back");
  assert.ok(b.options.find((o) => o.config === "Oak").gain.life > 0, "Oak's life shows up in PoB's numbers");
  assert.ok(b.options.find((o) => o.config === "Kraityn").gain.ms > 0, "Kraityn's movement speed too");
  const p = plan.milestones.pantheon;
  assert.equal(p.gods.length, 12);
  assert.equal(p.gods.filter((g) => g.major).length, 4, "major gods from PoB's Pantheon data");
  assert.ok(p.gods.every((g) => g.act >= 6 && g.act <= 10));
});

test("levelling_plan: resist checkpoint follows PoB's uncapped totals and the cited penalty", async () => {
  const r = plan.checkpoints.resists;
  assert.equal(r.expected, 0);
  assert.equal(r.nextAfterAct, 5);
  assert.equal(r.nextPenalty, -30);
  const stats = (await link.call("key_stats", { fields: ["FireResistTotal"] })).stats;
  const fire = r.elements.find((e) => e.name === "Fire");
  assert.equal(fire.now, stats.FireResist);
  assert.equal(fire.after, Math.min(stats.FireResistTotal - 30, fire.max));
  // The same as asking PoB with the penalty switched on.
  const sim = await link.call("what_if", { ops: [{ op: "config", values: { resistancePenalty: -30 } }] });
  assert.equal(fire.after, sim.after.FireResist);
  assert.match(r.source.url, /Resistance/);
});

test("levelling_plan: next steps for level 34, build unchanged afterwards", async () => {
  assert.ok(plan.next.length >= 2 && plan.next.length <= 8);
  assert.ok(plan.next.some((s) => s.kind === "lab" || s.kind === "quest points"));
  const before = (await link.call("key_stats")).stats;
  const nxt = await link.call("levelling_next", {});
  assert.deepEqual(nxt.next, (await link.call("levelling_next", {})).next, "stable answer");
  const afterStats = (await link.call("key_stats")).stats;
  assert.deepEqual(afterStats, before, "the plan never changes the build");
});

test("levelling_plan: a guide's levelling stages give swaps, links and lab nodes", async () => {
  const guide = {
    name: "Guide - test", config: { bandit: "Alira", pantheonMajorGod: "Solaris" },
    stages: [
      { index: 1, title: "Act 1-2", points: 20, level: 20, act: 2, passives: [{ id: 1, name: "Test Notable", type: "Notable", point: 12, level: 12 }], small: 18,
        asc: [], gems: [{ name: "Freezing Pulse", support: false }, { name: "Arcane Surge", support: true }], skills: [{ name: "Freezing Pulse", req: 1 }],
        main: { skill: "Freezing Pulse", links: 3, supports: ["Arcane Surge"] } },
      { index: 2, title: "Act 3-10", points: 80, level: 60, act: 8, passives: [], small: 60, asc: ["First", "Second", "Third", "Fourth"],
        gems: [{ name: "Vortex", support: false }], skills: [{ name: "Vortex", req: 28 }], main: { skill: "Vortex", links: 4, supports: [] } },
    ],
  };
  const g = await link.call("levelling_plan", { guide, simulate: false });
  assert.equal(g.from, "guide");
  const swaps = g.acts.flatMap((a) => a.swaps);
  assert.deepEqual(swaps.map((s) => [s.from, s.to]), [["Freezing Pulse", "Vortex"]]);
  assert.ok(swaps[0].level >= 28, "a swap waits for the gem's level");
  const fp = g.acts[0].gems.find((x) => x.name === "Freezing Pulse");
  assert.match(fp.text, /Act 1 quest reward: Enemy at the Gate/, "Witch gets Freezing Pulse from the Act 1 quest");
  assert.deepEqual(g.milestones.labs[0].nodes, ["First", "Second"]);
  assert.deepEqual(g.milestones.labs[1].nodes, ["Third", "Fourth"]);
  assert.equal(g.milestones.bandit.guide, "Alira");
  assert.equal(g.milestones.pantheon.guide.major, "Solaris");
  assert.ok(g.acts.flatMap((a) => a.links).some((l) => l.links === 4 && l.skill === "Vortex"));
});

test("levelling text: short answer and act-by-act plan, cited, with PoB's numbers", async () => {
  const { levellingPlan, nextText, planText, levellingSyncLine } = await import("../build/levelling.js");
  const short = nextText(await levellingPlan(context.pob, {}));
  assert.match(short, /^LEVELLING: Witch \(Occultist\) level 34, Act \d/);
  assert.match(short, /NEXT:\n1\. \[/);
  assert.match(short, /Facts: poewiki\.net \(CC BY-NC-SA 3\.0\), read \d{4}-\d\d-\d\d, for game \d+\.\d+/);
  const full = planText(await levellingPlan(context.pob, { plan: true }));
  for (const part of ["ACT BY ACT", "- Act 1 (levels 1-13)", "MILESTONES", "Normal Labyrinth (monster level 33)", "Bandit (Act 2)", "Pantheon (from Act 6)",
    "Quest passive points: 23", "GEAR CHECKPOINTS", "Boots:", "Sockets by item level: 4 from ilvl 25"]) assert.ok(full.includes(part), `plan has "${part}"`);
  assert.match(full, /Oak: \+40 to maximum Life -> PoB: DPS [+-][\d.]+%, EHP [+-]/);
  assert.ok(full.length < 9000, `plan stays readable (${full.length} chars)`);
  const line = await levellingSyncLine(context.pob);
  assert.match(line, /^LEVELLING: level 34 in Act \d - next: /);
});

test("guide { levelling }: the public tool gives the next steps and the plan, read-only", async () => {
  const next = await ok("guide", { levelling: "next" });
  assert.match(next, /^LEVELLING: Witch \(Occultist\) level 34, Act \d/);
  const full = await ok("guide", { levelling: "plan" });
  assert.match(full, /ACT BY ACT/);
  const saved = process.env.POB_READ_ONLY;
  process.env.POB_READ_ONLY = "1";
  try { assert.match(await ok("guide", { levelling: "next" }), /NEXT:/, "allowed with edits off"); } finally {
    if (saved === undefined) delete process.env.POB_READ_ONLY; else process.env.POB_READ_ONLY = saved;
  }
});

test("Overview Levelling card: draws headless with the global build unset, follows the Guide tab, hides at 90", async () => {
  const { spawnSync } = await import("node:child_process");
  const guideMode = await import("../build/guideMode.js");
  const fixture = fs.readFileSync(path.join(here, "fixtures", "occ-vortex.xml"), "utf8");
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "agent-levcard-"));
  fs.writeFileSync(path.join(dir, "guide.xml"), guideMode.mergeStages([{ stage: "Act 1-3", xml: fixture }, { stage: "Endgame", xml: fixture }]));
  const runtime = path.join(root, "PathOfBuilding", "runtime");
  const env = {
    ...process.env,
    LUA_PATH: `${path.join(runtime, "lua", "?.lua")};${path.join(runtime, "lua", "?", "init.lua")};;`,
    LUA_CPATH: `${path.join(runtime, process.platform === "win32" ? "?.dll" : "?.so")};;`,
  };
  const exe = path.join(root, "luajit", process.platform === "win32" ? "luajit.exe" : "luajit");
  const r = spawnSync(exe, [path.join(here, "levellingcard.lua"), path.join(here, "fixtures", "occ-vortex.xml"), path.join(dir, "guide.xml"), dir],
    { cwd: path.join(root, "PathOfBuilding", "src"), env, encoding: "utf8", timeout: 240_000 });
  assert.equal(r.status, 0, `levellingcard.lua failed:\n${r.stdout}\n${(r.stderr ?? "").slice(-1500)}`);
  assert.match(r.stdout, /levellingcard ok: \d+ steps, act \d+, guide Guide - Test/);
});

